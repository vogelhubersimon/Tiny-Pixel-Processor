-- File: UartRx-ea.vhd
-- Contributors: Thomas Lindinger
-- Description: Receives UART frames, samples the data bits, and outputs each valid data byte.

library ieee;
use ieee.std_logic_1164.all;
use ieee.numeric_std.all;
use ieee.math_real.all;

use work.Global.all;

entity UartRx is
    generic (
        gClkFrequency : natural := cClkFrequency;
        gBaudrate : natural := cBaudRate;
        gDataBits : natural := cDataBits
    );
    port (
        iClk : in std_ulogic;
        inRstAsync : in std_ulogic;
        iRx : in std_ulogic;
        oData : out aUartData;
        oValid : out std_ulogic
    );
end entity UartRx;

architecture Rtl of UartRx is

    type aState is (Idle, Start, Data, Stop);

    constant cClocksPerBaud : natural := gClkFrequency / gBaudrate;
    constant cBaudStrobeBits : natural := natural(ceil(log2(real(cClocksPerBaud))));

    type aRegSet is record
        State : aState;
        DataBitCount : natural range 0 to gDataBits - 1;
        BaudStrobe : std_ulogic;
        BaudStrobeCounter : unsigned(cBaudStrobeBits - 1 downto 0);
        Data : aUartData;
        Valid : std_ulogic;
    end record;

    constant cInitValR : aRegSet := (
        State => Idle,
        DataBitCount => 0,
        BaudStrobe => '0',
        BaudStrobeCounter => to_unsigned(0, cBaudStrobeBits),
        Data => (others => '0'),
        Valid => '0'
    );

    signal R, NxR : aRegSet;

begin

    process (iClk, inRstAsync)
    begin
        if inRstAsync = not('1') then
            R <= cInitValR;
        elsif rising_edge(iClk) then
            R <= NxR;
        end if;
    end process;

    process (all)
    begin

        NxR <= R;
        NxR.Valid <= '0';

        -- Strobe generator
        NxR.BaudStrobeCounter <= R.BaudStrobeCounter + 1;
        NxR.BaudStrobe <= '0';
        if R.BaudStrobeCounter = cClocksPerBaud - 1 then
            NxR.BaudStrobeCounter <= to_unsigned(0, cBaudStrobeBits);
            NxR.BaudStrobe <= '1';
        end if;

        -- state machine for uart recieve sequence
        case R.State is
            when Idle =>
                if iRx = '0' then
                    NxR.BaudStrobeCounter <= to_unsigned(cClocksPerBaud / 2, cBaudStrobeBits);
                    NxR.State <= Start;
                    NxR.BaudStrobe <= '0';
                end if;

            when Start =>
                if R.BaudStrobe = '1' then
                    NxR.State <= Data;
                    NxR.DataBitCount <= 0;
                end if;

            when Data =>
                if R.BaudStrobe = '1' then
                    NxR.Data(R.DataBitCount) <= iRx;
                    if R.DataBitCount = gDataBits - 1 then
                        NxR.State <= Stop;
                    else
                        NxR.DataBitCount <= R.DataBitCount + 1;
                    end if;
                end if;

            when Stop =>
                if R.BaudStrobe = '1' then
                    if iRx = '1' then -- stop bit
                        NxR.Valid <= '1';
                    end if;
                    NxR.State <= Idle;
                end if;
                
            when others => null;
        end case;
    end process;

    oData <= R.Data;
    oValid <= R.Valid;

end architecture;

-- File: UartInterpreter-ea.vhd
-- Contributors: Thomas Lindinger
-- Description: Decodes UART command bytes into instruction-memory writes and time-counter updates.

library ieee;
use ieee.std_logic_1164.all;
use ieee.numeric_std.all;
use ieee.math_real.all;

use work.Global.all;

entity UartInterpreter is
    generic (
        gClkFrequency : natural := cClkFrequency;
        gDataBits : natural := cDataBits;
        gDataBytes : natural := cDataBytes
    );
    port (
        iClk : in std_ulogic;
        inRstAsync : in std_ulogic;
        iData : in aUartData;
        iValid : in std_ulogic;
        oWE : out std_ulogic;
        oAddr : out aInstrAddr;
        oInstr : out aInstruction;
        oTimeCounterValid : out std_ulogic;
        oTimeCounter : out aTimeRegister--;
    );
end entity UartInterpreter;

architecture Rtl of UartInterpreter is

    type aState is (Command, InstructionHigh, InstructionLow, Output);
    type aByte is (CommandByte, InstructionHighByte, InstructionLowByte);
    type aInputData is array(aByte range <>) of std_ulogic_vector;

    type aRegSet is record
        State : aState;
        Data : aInputData(CommandByte to InstructionLowByte)(gDataBits - 1 downto 0);
        
        -- Instruction memory interface
        WE : std_ulogic;
        Instr : aInstruction;
        Addr : aInstrAddr;

        -- Time Counter value
        TimeCounterValid : std_ulogic;
        TimeCounter : aTimeRegister;

    end record;

    constant cInitValR : aRegSet := (
        State => Command,
        Data => (others => (others => '0')),
        WE => '0',
        Addr => (others => '0'),
        Instr => (others => '0'),
        TimeCounterValid => '0',
        TimeCounter => (others => '0')
    );

    signal R, NxR : aRegSet;

begin

    process (iClk, inRstAsync)
    begin
        if inRstAsync = not('1') then
            R <= cInitValR;
        elsif rising_edge(iClk) then
            R <= NxR;
        end if;
    end process;

    process (all)
    begin

        -- default assignments
        NxR <= R;
        NxR.WE <= '0';
        NxR.TimeCounterValid <= '0';

        -- state machine for command iterpreting sequence
        case R.State is
            when Command =>
            
                if iValid = '1' then
                    NxR.Data(CommandByte) <= iData;
                    if (iData(gDataBits - 1) = '1') then -- Instruction
                        NxR.State <= InstructionHigh;
                    else
                        NxR.State <= Output; -- received a Command
                    end if;
                end if;

            when InstructionHigh =>

                if iValid = '1' then
                    NxR.Data(InstructionHighByte) <= iData;
                    NxR.State <= InstructionLow;
                end if;

            when InstructionLow =>
            
                if iValid = '1' then
                    NxR.Data(InstructionLowByte) <= iData;
                    NxR.State <= Output;
                end if;

            when Output =>

                if (R.Data(CommandByte)(gDataBits - 1 downto gDataBits - 2) = "10") then -- Instruction
                    NxR.WE <= '1';
                    NxR.Addr <= R.Data(CommandByte)(4 downto 0);
                    NxR.Instr <= R.Data(InstructionHighByte) & R.Data(InstructionLowByte);
                elsif (R.Data(CommandByte)(gDataBits - 1 downto gDataBits - 2) = "01") then -- Command to change Time Counter
                    NxR.TimeCounterValid <= '1';
                    NxR.TimeCounter <= to_unsigned(to_integer(unsigned(R.Data(CommandByte)(5 downto 0))), 6);
                end if;

                NxR.State <= Command;

            when others => null;
        end case;
    end process;

    oWE <= R.WE;
    oAddr <= R.Addr;
    oInstr <= R.Instr;
    oTimeCounterValid <= R.TimeCounterValid;
    oTimeCounter <= R.TimeCounter;

end architecture;

-- File: PixelProcessorFSMD-ea.vhd
-- Contributors: Thomas Lindinger, Patrick Pollak, Julian Schlager, Simon Vogelhuber
-- Components:
--   UART Receiver: Receives serial data and converts it into bytes.
--   UART Interpreter: Decodes received commands, instructions, addresses, and timing values.
--   Instruction Memory: Stores the program and supports instruction updates through UART.
--   Program Counter: Selects the instruction that is fetched and executed by the CPU.
--   VGA Timing Generator: Produces pixel coordinates, synchronization pulses, and video blanking.
--   FSMD State Register: Stores the register file, decoded instruction, flags, and timing state.
--   Instruction Decoder and ALU: Executes arithmetic, logic, comparison, and output operations.
--   Time and Random Logic: Generates frame-based time values and pseudo-random register values.
--   Waveform LUTs: Provide sine, ramp, and sawtooth values for pixel calculations.
--   Bitmap ROM Logic: Reads stored graphics and converts their pixels into color values.
-- Description: Executes a programmable pixel-processing instruction sequence for each display
--              region and converts the results into synchronized VGA color output.

library ieee;
use ieee.std_logic_1164.all;
use ieee.numeric_std.all;

library work;
use work.Global.all;
use work.VGA_Package.all;
use work.BitmapRomFH.all;
use work.BitmapRomHSD.all;
use work.BitmapRomTT.all;
use work.BitmapRomCredits.all;
use work.BitmapRomFlagpole.all;
use work.BitmapRomHSD_ESD.all;

entity PixelCPU is
    port (
        iClk : in std_ulogic;           -- clk input
        inRstAsync : in std_ulogic;     -- async reset input, active low

        -- Uart Inputs
        iRx : in std_ulogic;

        -- VGA Outputs
        oHsync : out std_ulogic;
        oVsync : out std_ulogic;
        oVideoOn : out std_ulogic;
        oPixelColor : out aPixelColor
    );
end entity PixelCPU;

architecture rtl of PixelCPU is

    -- UART Signals
    signal sUart_WritePulse, sUart_CpuStart : std_ulogic;
    signal sUart_AdressSelect : aInstrAddr;
    signal sUart_Instr : aInstruction;
    signal sUart_TimeCounterValid : std_ulogic;
    signal sUart_TimeCounter : aTimeRegister;

    -- UartRx to UartInterpreter
    signal sUart_Data : aUartData;
    signal sUart_Valid : std_ulogic;

    -- Instruction Memory
    signal sInstrMem : aInstruction_mem;
    
    -- VGA Signals
    signal sVGA_Strobe : std_ulogic;
    signal sVGA_HSync : std_ulogic;
    signal sVGA_VSync : std_ulogic;
    signal sVGA_VideoOn : std_ulogic;
    signal sVGA_PixelX : pixel_x_t;
    signal sVGA_PixelY : pixel_y_t;

    -- Programm Counter:
    signal sCPU_Pc : integer range 0 to cNumInstr - 1;

    -- State Register
    type aStateReg is record

        -- Y Counter for counting how many times we reached the end of a dekapixel line, used for generating the dekapixel y coordinate
        CPU_YCounter : unsigned(3 downto 0); 

        -- Run CPU
        -- tells the cpu to run cNumInstr - 1 cycles before the visible area starts that it should start executing instructions, 
        -- so that the first instruction is executed when the first pixel is being drawn
        CPU_Run : std_ulogic;

        -- Regfile
        CPU_RegFile : aRegisterFile;

        -- Time related registers
        TIME_Counter : aTimeRegister; -- for counting frames
        TIME_Compare : aTimeRegister; -- for comparing the counter

        -- Conditional Flags
        CPU_Cond : aCond;

        -- Color Output
        CPU_ODR : aPixelColor;

        -- Instruciton Register to hold the previously fetched instruction, so that it can be executed in the next cycle while the next instruction is being fetched
        CPU_SavedInstr : aInstruction;
        
        -- Saved decoded instruction fields of the previously fetched insturctions (timing related reasons)
        Instr_Rd, Instr_Rs : aRegFileIdx;
        Instr_Imm : aImmediate;
        Instr_Cond : aCond;
        Instr_Opcode : aOpcode;

    end record aStateReg;

    -- Initial state of the state register
    constant RInitState : aStateReg := (
        CPU_YCounter => (others => '0'),
        CPU_Run => '0',
        CPU_SavedInstr => (others => '0'),
        CPU_RegFile => (others => (others => '0')),
        CPU_Cond => cAlways,
        TIME_Counter => (others => '0'),
        TIME_Compare => cFrameCountVal,
        CPU_ODR => (others => '0'),
        Instr_Rd => 0,
        Instr_Rs => 0,
        Instr_Imm => (others => '0'),
        Instr_Cond => cAlways,
        Instr_Opcode => (others => '0')
    );

    -- signal for the next state logic of the state register
    signal xR, R : aStateReg;
begin
    -- due to timing related issues caused by the FSMD creating huge fanouts
    -- the instruction memory is implemented inside a process
    instr_mem : process (iClk, inRstAsync) is
    begin
        if inRstAsync = not('1') then
            sInstrMem <= cInstrMemInitState;
        elsif rising_edge(iClk) then
            if sUart_WritePulse = '1'and (unsigned(sUart_AdressSelect)) < cNumInstr - 1 then
                sInstrMem(to_integer(unsigned(sUart_AdressSelect))) <= sUart_Instr;
            end if;
        end if;
    end process instr_mem;

    -- for the same reason the pc logic lives inside this process
    program_counter : process (iClk, inRstAsync) is
    begin
        if inRstAsync = not('1') then
            sCPU_Pc <= 0;
        elsif rising_edge(iClk) then
            if R.CPU_RUN = '1' then
                if sCPU_Pc = cNumInstr - 1 then
                    sCPU_Pc <= 0;
                else
                    sCPU_Pc <= sCPU_Pc + 1;
                end if;
            else
                sCPU_Pc <= 0;
            end if;
        end if;
    end process program_counter;

    -- same goes for the VGA signal generation logic
    vga : process (iClk, inRstAsync) is
    begin
        if inRstAsync = not('1') then
            sVGA_Strobe <= '0';
            sVGA_HSync <= VGA_PULSE_INACTIVE;
            sVGA_VSync <= VGA_PULSE_INACTIVE;
            sVGA_VideoOn <= '0';
            sVGA_PixelX <= (others => '0');
            sVGA_PixelY <= (others => '0');
        elsif rising_edge(iClk) then

            -- =================================================================
            -- VGA Signal Generation Logic
            -- ---------------------------
            -- VGA_Strobe 
            --      is a singal that halfs the clock frequency for the VGA 
            --      signal generation, because the VGA timing  requirements are 
            --      half the frequency of the system clock
            -- VGA_PixelX, VGA_PixelY
            --      are counters that count the current pixel position, and are
            --      used for generating the sync pulses and the video on signal
            -- HSYNC, VSYNC
            --      are generated based on the current pixel position and the
            --      VGA timing requirements.
            -- VideoOn
            --      is used for blanking the screen outside of the visible area
            -- =================================================================
            sVGA_Strobe <= not sVGA_Strobe;

            sVGA_HSync <= VGA_PULSE_INACTIVE;
            sVGA_VSync <= VGA_PULSE_INACTIVE;

            if sVGA_Strobe = '1' then
                -- Counter logic
                sVGA_PixelX <= sVGA_PixelX + 1;
                if sVGA_PixelX = VGA_640x480.h_whole_line - 1 then
                    sVGA_PixelX <= (others => '0');

                    if sVGA_PixelY = VGA_640x480.v_whole_frame - 1 then
                        sVGA_PixelY <= (others => '0');
                    else
                        sVGA_PixelY <= sVGA_PixelY + 1;
                    end if;
                end if;
            end if;

            -- =================================================================
            -- SYNC Pulse Generation Logic
            -- =================================================================
            if sVGA_PixelX >= VGA_640x480.h_visible_area + VGA_640x480.h_front_porch and
                sVGA_PixelX < VGA_640x480.h_whole_line - VGA_640x480.h_back_porch then
                sVGA_HSync <= VGA_PULSE_ACTIVE;
            end if;

            if sVGA_PixelY >= VGA_640x480.v_visible_area + VGA_640x480.v_front_porch and
                sVGA_PixelY < VGA_640x480.v_whole_frame - VGA_640x480.v_back_porch then
                sVGA_VSync <= VGA_PULSE_ACTIVE;
            end if;

            -- =================================================================
            -- VIDEO ON LOGIC
            -- --------------
            -- Checks if the current pixel position is within the visible area.
            -- =================================================================
            if sVGA_PixelX < VGA_640x480.h_visible_area
                and sVGA_PixelY < VGA_640x480.v_visible_area then
                sVGA_VideoOn <= '1';
            else
                sVGA_VideoOn <= '0';
            end if;

        end if;
    end process vga;

    -- FSMD Register Process
    reg : process (iClk, inRstAsync) is
    begin
        if inRstAsync = not('1') then
            R <= RInitState;
        elsif rising_edge(iClk) then
            R <= xR;
        end if;
    end process reg;

    -- FSMD Combinational Logic
    comb : process (all) is
    begin
        xR <= R;

        -- =================================================================
        -- Instruction Execution Logic (hell yeah - the ALU)
        -- ---------------------------
        -- Here the instructions are excecuted in one clock cycle based on 
        -- the opcode. 
        -- =================================================================
        if (R.Instr_Cond = cAlways or R.CPU_Cond = R.Instr_Cond) then
            case R.Instr_Opcode is
                when cOpSet =>
                    xR.CPU_RegFile(R.Instr_Rd) <= R.Instr_Imm;
                when cOpMov =>
                    xR.CPU_RegFile(R.Instr_Rd) <= R.CPU_RegFile(R.Instr_Rs);
                when cOpAdd =>
                    xR.CPU_RegFile(R.Instr_Rd) <= std_ulogic_vector(unsigned(R.CPU_RegFile(R.Instr_Rd)) + unsigned(R.CPU_RegFile(R.Instr_Rs)));
                when cOpSub =>
                    xR.CPU_RegFile(R.Instr_Rd) <= std_ulogic_vector(unsigned(R.CPU_RegFile(R.Instr_Rd)) - unsigned(R.CPU_RegFile(R.Instr_Rs)));
                when cOpSl =>
                    xR.CPU_RegFile(R.Instr_Rd) <= std_ulogic_vector(unsigned(R.CPU_RegFile(R.Instr_Rd)) sll to_integer(unsigned(R.Instr_Imm)));
                when cOpSr =>
                    xR.CPU_RegFile(R.Instr_Rd) <= std_ulogic_vector(unsigned(R.CPU_RegFile(R.Instr_Rd)) srl to_integer(unsigned(R.Instr_Imm)));
                when cOpAnd =>
                    xR.CPU_RegFile(R.Instr_Rd) <= R.CPU_RegFile(R.Instr_Rd) and R.CPU_RegFile(R.Instr_Rs);
                when cOpNand =>
                    xR.CPU_RegFile(R.Instr_Rd) <= R.CPU_RegFile(R.Instr_Rd) nand R.CPU_RegFile(R.Instr_Rs);
                when cOpOr =>
                    xR.CPU_RegFile(R.Instr_Rd) <= R.CPU_RegFile(R.Instr_Rd) or R.CPU_RegFile(R.Instr_Rs);
                when cOpNor =>
                    xR.CPU_RegFile(R.Instr_Rd) <= R.CPU_RegFile(R.Instr_Rd) nor R.CPU_RegFile(R.Instr_Rs);
                when cOpXor =>
                    xR.CPU_RegFile(R.Instr_Rd) <= R.CPU_RegFile(R.Instr_Rd) xor R.CPU_RegFile(R.Instr_Rs);
                when cOpOut =>
                    xR.CPU_ODR <= R.CPU_RegFile(R.Instr_Rs);
                when cOpSin =>
                    if R.CPU_RegFile(R.Instr_Rs)(4) = '0' then
                        xR.CPU_RegFile(R.Instr_Rd) <= cSineLUT(to_integer(unsigned(R.CPU_RegFile(R.Instr_Rs)(3 downto 0))));
                    else
                        xR.CPU_RegFile(R.Instr_Rd) <= cSineLUT(15 - to_integer(unsigned(R.CPU_RegFile(R.Instr_Rs)(3 downto 0))));
                    end if;
                when cOpRamp =>
                    if unsigned(R.CPU_RegFile(R.Instr_Rs)) < to_unsigned(16, 6) then
                        xR.CPU_RegFile(R.Instr_Rd) <= cRampLUT(to_integer(unsigned(R.CPU_RegFile(R.Instr_Rs)(3 downto 0))));
                    elsif unsigned(R.CPU_RegFile(R.Instr_Rs)) < to_unsigned(32, 6) then
                        xR.CPU_RegFile(R.Instr_Rd) <= cRampLUT(15 - to_integer(unsigned(R.CPU_RegFile(R.Instr_Rs)(3 downto 0))));
                    elsif unsigned(R.CPU_RegFile(R.Instr_Rs)) < to_unsigned(48, 6) then
                        xR.CPU_RegFile(R.Instr_Rd) <= cRampLUT(to_integer(unsigned(R.CPU_RegFile(R.Instr_Rs)(3 downto 0))));
                    else
                        xR.CPU_RegFile(R.Instr_Rd) <= cRampLUT(15 - to_integer(unsigned(R.CPU_RegFile(R.Instr_Rs)(3 downto 0))));
                    end if;
                when cOpSaw =>
                    xR.CPU_RegFile(R.Instr_Rd) <= cRampLUT(to_integer(unsigned(R.CPU_RegFile(R.Instr_Rs)(3 downto 0))) mod 16);
                when cOpComp =>
                    if unsigned(R.CPU_RegFile(R.Instr_Rd)) = unsigned(R.CPU_RegFile(R.Instr_Rs)) then
                        xR.CPU_Cond <= cEqual; 
                    elsif unsigned(R.CPU_RegFile(R.Instr_Rd)) < unsigned(R.CPU_RegFile(R.Instr_Rs)) then
                        xR.CPU_Cond <= cLess;
                    elsif unsigned(R.CPU_RegFile(R.Instr_Rd)) > unsigned(R.CPU_RegFile(R.Instr_Rs)) then
                        xR.CPU_Cond <= cGreater;
                    else
                        xR.CPU_Cond <= cAlways;
                    end if;
                when cOpFHLogo =>
                        -- Bitmap 64x48 so RX, RY can be used to index into the bitmap rom
                        -- cBitmapRom( Y COORDINATE) (XCOORDINATE)
                        if (to_integer(unsigned(R.CPU_RegFile(cIdxRegY))) < 27) then
                            if cBitmapRomFH(to_integer(unsigned(R.CPU_RegFile(cIdxRegY))))(to_integer(unsigned(R.CPU_RegFile(cIdxRegX)))) = '0' then
                                xR.CPU_RegFile(R.Instr_Rd) <= "110000";
                            else
                                xR.CPU_RegFile(R.Instr_Rd) <= "111111";
                            end if;
                        else
                            if cBitmapRomFH(to_integer(unsigned(R.CPU_RegFile(cIdxRegY))))(to_integer(unsigned(R.CPU_RegFile(cIdxRegX)))) = '0' then
                                xR.CPU_RegFile(R.Instr_Rd) <= "000000";
                            else
                                xR.CPU_RegFile(R.Instr_Rd) <= "111111";
                            end if;
                        end if;
                when cOpHSDLogo =>
                    if cBitmapRomHSD(to_integer(unsigned(R.CPU_RegFile(cIdxRegY))))(to_integer(unsigned(R.CPU_RegFile(cIdxRegX)))) = '0' then
                        xR.CPU_RegFile(R.Instr_Rd) <= "000000";
                    else
                        xR.CPU_RegFile(R.Instr_Rd) <= "111111";
                    end if;
                when cOpTTLogo =>
                    if cBitmapRomTT(to_integer(unsigned(R.CPU_RegFile(cIdxRegY))))(to_integer(unsigned(R.CPU_RegFile(cIdxRegX)))) = '0' then
                        xR.CPU_RegFile(R.Instr_Rd) <= "000000";
                    else
                        xR.CPU_RegFile(R.Instr_Rd) <= "111111";
                    end if;
                when cOpCredits =>
                    if cBitmapRomCredits(to_integer(unsigned(R.CPU_RegFile(cIdxRegY))))(to_integer(unsigned(R.CPU_RegFile(cIdxRegX)))) = '0' then
                        xR.CPU_RegFile(R.Instr_Rd) <= "000000";
                    else
                        xR.CPU_RegFile(R.Instr_Rd) <= "111111";
                    end if;
                when cOpFlagP =>
                    if cBitmapRomFlagpole(to_integer(unsigned(R.CPU_RegFile(cIdxRegY))))(to_integer(unsigned(R.CPU_RegFile(cIdxRegX)))) = '0' then
                        xR.CPU_RegFile(R.Instr_Rd) <= "000000";
                    else
                        if (to_integer(unsigned(R.CPU_RegFile(cIdxRegY))) > 9) and (to_integer(unsigned(R.CPU_RegFile(cIdxRegX))) > 16) and
                        (to_integer(unsigned(R.CPU_RegFile(cIdxRegY))) < 30) and (to_integer(unsigned(R.CPU_RegFile(cIdxRegX))) < 53) then
                            xR.CPU_RegFile(R.Instr_Rd) <= "101010";
                        else
                            xR.CPU_RegFile(R.Instr_Rd) <= "111111";
                        end if;
                    end if;
                when cOpHSDESD =>
                    if cBitmapRomHSD_ESD(to_integer(unsigned(R.CPU_RegFile(cIdxRegY))))(to_integer(unsigned(R.CPU_RegFile(cIdxRegX)))) = '0' then
                        xR.CPU_RegFile(R.Instr_Rd) <= "000000";
                    else
                        xR.CPU_RegFile(R.Instr_Rd) <= "111111";
                    end if;
                    
                when others => null; -- nop gets implicitly handled
            end case;
        end if;

        -- =================================================================
        -- RUN_CPU Setup Logic
        -- -------------
        -- the cpu should start running cNumInstr - 1 (or 10 pixels) before 
        -- the visible area starts, so that when the first pixel is being 
        -- drawn, the first instruction is already executed and theres data 
        -- in ODR. Also the "pipelining stages" need to be taken into account
        -- =================================================================
        if sVGA_PixelX > (VGA_640x480.h_whole_line - 12)
            or sVGA_PixelX < VGA_640x480.h_visible_area then
            xR.CPU_Run <= '1';
        else
            xR.CPU_Run <= '0';
        end if;

        -- =================================================================
        -- RUN_CPU Logic
        -- --------------
        -- In here the instructions are excecuted based on the current
        -- count of the program counter. The PC counts up each strobe when
        -- the cpu is running, and resets when it reaches the number of 
        -- instructions for a pixel (cNumInstr) or when the cpu is not running. 
        -- 
        -- Also the registers that are used for the dekapixel logic 
        -- (RegFile(4) and RegFile(5)) are generated.
        -- =================================================================
        if R.CPU_RUN = '1' then

            -- Increment every 10 pixels
            if sCPU_Pc = cNumInstr - 1 then
                xR.CPU_RegFile(cIdxRegX) <= std_ulogic_vector(unsigned(R.CPU_RegFile(cIdxRegX)) + 1);
            end if;

        else -- CPU is not running, reset PC and DekapixelX counter
            xR.CPU_RegFile(cIdxRegX) <= (others => '0');

            -- =============================================================
            -- Y Coordinate mod counting logic (regfile(5) and Y_Counter)
            -- --------------
            -- To get the current dekapixel y coordinate, we need to count 
            -- how many times we reached the end of a dekapixel line. For 
            -- that we use a counter that counts from 0 to 9, and when it
            -- reaches 9, we reset it and increment the dekapixel y coordinate
            -- =============================================================
            if sVGA_PixelX = VGA_640x480.h_whole_line - 20
                and sVGA_PixelY < VGA_640x480.v_visible_area
                and sVGA_Strobe = '1' 
                then
                -- increment Y counter
                xR.CPU_YCounter <= R.CPU_YCounter + 1;

                -- when Y counter reaches 10, reset it and increment Dekapixel Y counter
                if R.CPU_YCounter = to_unsigned(9, 4) then
                    xR.CPU_YCounter <= (others => '0');
                    xR.CPU_RegFile(cIdxRegY) <= std_ulogic_vector(unsigned(R.CPU_RegFile(cIdxRegY)) + 1);

                    if R.CPU_RegFile(cIdxRegY) = std_ulogic_vector(to_unsigned(47, 6)) then
                        xR.CPU_RegFile(cIdxRegY) <= (others => '0');
                    end if;
                end if;
            end if;
        end if;

        -- =================================================================
        -- Time Register Logic
        -- -------------------
        -- Here the TIME_Counter is compared to the compare register.
        -- when the counter reaches the compare value, it resets and
        -- increments the time register (RegFile(6) == REGT). 
        -- REGT is allowed to overflow.
        -- =================================================================
        if sVGA_PixelX = 0 and sVGA_PixelY = VGA_640x480.v_whole_frame - 1 then
            xR.TIME_Counter <= R.TIME_Counter + 1;
            if R.TIME_Counter = R.TIME_Compare then
                xR.TIME_Counter <= (others => '0');
                xR.CPU_RegFile(cIdxRegT) <= std_ulogic_vector(unsigned(R.CPU_RegFile(cIdxRegT)) + 1);
            end if;
        end if;

        if sUart_TimeCounterValid = '1' then
            xR.TIME_Compare <= sUart_TimeCounter;
        end if;

        -- =================================================================
        -- Rand Register Logic
        -- -------------------
        -- Here the random register (RegFile(7) == REGR) is generated.
        -- For that we use a linear feedback shift register, that takes the current value of the register and the value of the Y counter as input, 
        -- to generate a new random value each time a new Y dekapixel is reached.
        -- =================================================================

        if sCPU_Pc = cNumInstr - 1 then
            if sVGA_PixelX > VGA_640x480.h_visible_area then
                xR.CPU_RegFile(cIdxRegR) <= lfsrand(std_ulogic_vector(unsigned(R.CPU_RegFile(cIdxRegY)) + 1));
            else
                xR.CPU_RegFile(cIdxRegR) <= lfsrand(R.CPU_RegFile(cIdxRegR));
            end if;
        end if;

        -- =================================================================
        -- Instruction Fetch Logic
        -- -------------------
        -- Here the instruction is fetched from the instruction memory based on the current program counter, and saved in a register to be executed in the next cycle. 
        -- The instruction is also decoded into its fields and saved in registers for timing related reasons.
        -- =================================================================

        xR.CPU_SavedInstr <= sInstrMem(sCPU_Pc);

        xR.Instr_Rd <= to_integer(unsigned(R.CPU_SavedInstr(10 downto 8)));
        xR.Instr_Rs <= to_integer(unsigned(R.CPU_SavedInstr(7 downto 5)));
        xR.Instr_Imm <= R.CPU_SavedInstr(7 downto 2);
        xR.Instr_Cond <= R.CPU_SavedInstr(1 downto 0);
        xR.Instr_Opcode <= R.CPU_SavedInstr(15 downto 11);
    end process comb;

    -- Output Assignments
    oVideoOn <= sVGA_VideoOn;
    oPixelColor <= R.CPU_ODR;
    oVSync <= sVGA_VSync;
    oHSync <= sVGA_HSync;

    -- UartRx and UartInterpreter Instantiation
    UartRx : entity work.UartRx(rtl)
        port map(
            iClk => iClk,
            inRstAsync => inRstAsync,
            iRx => iRx,
            oData => sUart_Data,
            oValid => sUart_Valid
        );

    UartInterpreter_inst : entity work.UartInterpreter(Rtl)
        port map(
            iClk => iClk,
            inRstAsync => inRstAsync,
            iData => sUart_Data,
            iValid => sUart_Valid,
            oWE => sUart_WritePulse,
            oAddr => sUart_AdressSelect,
            oInstr => sUart_Instr,
            oTimeCounterValid => sUart_TimeCounterValid,
            oTimeCounter => sUart_TimeCounter
        );

end architecture rtl;

-- File: TinyPixelProcessor-ea.vhd
-- Contributors:
-- Description: Wraps the PixelCPU and synchronizes the asynchronous reset and UART input
--              before forwarding the generated VGA signals and pixel color.

library ieee;
use ieee.std_logic_1164.all;
use ieee.numeric_std.all;
use ieee.math_real.all;

library work;
use work.Global.all;

entity TinyPixelProcessor is
    port (
        iClk        : in std_ulogic;    -- clk input
        inRstAsync  : in std_ulogic;    -- asynchronous reset input, active low

        -- UART input
        iRx         : in std_ulogic;

        -- VGA output
        oHSync      : out std_ulogic;
        oVSync      : out std_ulogic;
        oVideoOn    : out std_ulogic;
        oPixelColor : out aPixelColor
    );
end entity TinyPixelProcessor;

architecture Rtl of TinyPixelProcessor is
    -- Signals for reset synchronization
    signal nRstSynced: std_ulogic;
    signal nRstMayMeta : std_ulogic;
    
    -- Signals for UART synchronization
    signal RxSyncMayMeta : std_ulogic;
    signal RxSync : std_ulogic;

begin
    -- Instantiate the PixelProcessor
    PixelProcessor : entity work.PixelCPU(rtl)
    port map(
        iClk => iClk,
        inRstAsync => nRstSynced,
        iRx => RxSync,
        oHSync => oHSync,
        oVSync => oVSync,
        oVideoOn => oVideoOn,
        oPixelColor => oPixelColor
    );

    -- Reset synchronization process
    process(iClk, inRstAsync) is
    begin
        if inRstAsync = not('1') then
            nRstSynced <= '0';
            nRstMayMeta <= '0';
        elsif falling_edge(iClk) then
            nRstSynced <= nRstMayMeta;
            nRstMayMeta <= '1';
        end if;
    end process;

    -- UART synchronization process
    process (iClk, nRstSynced) is
    begin
        if nRstSynced = not('1') then
            RxSyncMayMeta <= '1';
            RxSync <= '1';
        elsif falling_edge(iClk) then
            RxSyncMayMeta <= iRx;
            RxSync <= RxSyncMayMeta;
        end if;
    end process;
    
    
end architecture;

