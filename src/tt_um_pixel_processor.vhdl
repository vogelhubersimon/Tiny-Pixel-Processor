Package body Global is

    function lfsrand(reg : in std_ulogic_vector(5 downto 0)) 
    return std_ulogic_vector is
    begin
        return reg(0) & (reg(5) xor reg(0)) & reg(4 downto 1);
    end function;

end Global;

